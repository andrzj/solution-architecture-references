#!/usr/bin/env python3
"""Generate assets/data/search-index.json and patch assets/js/main.js SEARCH_INDEX."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from site_index_lib import ROOT, build_search_entries

DATA_PATH = ROOT / "assets" / "data" / "search-index.json"
MAIN_JS = ROOT / "assets" / "js" / "main.js"

BEGIN = "// BEGIN SEARCH_INDEX (generated by scripts/build_search_index.py)"
END = "// END SEARCH_INDEX"


def format_js_entries(entries: list[dict[str, str]]) -> str:
    lines = [BEGIN, "const SEARCH_INDEX = ["]
    current_section = None
    for item in entries:
        section = item["section"]
        if section != current_section:
            lines.append(f"  // {section}")
            current_section = section
        title = json.dumps(item["title"])
        path = json.dumps(item["path"])
        section_js = json.dumps(item["section"])
        desc = json.dumps(item["description"])
        lines.append(
            f"  {{ title: {title}, path: {path}, section: {section_js}, description: {desc} }},"
        )
    lines.append("];")
    lines.append(END)
    return "\n".join(lines) + "\n"


def patch_main_js(block: str) -> None:
    text = MAIN_JS.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("main.js missing SEARCH_INDEX markers; add BEGIN/END comments.", file=sys.stderr)
        sys.exit(1)
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    trailing = 1 if end < len(text) and text[end] == "\n" else 0
    MAIN_JS.write_text(text[:start] + block + text[end + trailing :], encoding="utf-8")


def main() -> int:
    entries = build_search_entries()
    DATA_PATH.parent.mkdir(parents=True, exist_ok=True)
    DATA_PATH.write_text(
        json.dumps(entries, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    patch_main_js(format_js_entries(entries))
    print(f"Wrote {len(entries)} entries to {DATA_PATH.relative_to(ROOT)}")
    print(f"Patched {MAIN_JS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())